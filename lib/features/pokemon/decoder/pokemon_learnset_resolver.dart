  static int baseSpeciesId(GameAssetProfile profile, int pokemonId) {
    final maximumId = switch (profile.game) {
      PokemonAssetGame.redBlue || PokemonAssetGame.yellow => 151,
      PokemonAssetGame.gold ||
      PokemonAssetGame.silver ||
      PokemonAssetGame.crystal => 251,
      PokemonAssetGame.rubySapphire ||
      PokemonAssetGame.emerald ||
      PokemonAssetGame.fireRedLeafGreen => 386,
      _ => 0,
    };
    var current = pokemonId;
    while (true) {
      final parent = _parentSpecies[current];
      if (parent == null || parent > maximumId) return current;
      current = parent;
    }
  }

